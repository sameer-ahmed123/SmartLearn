# 1. ORIGINAL FUNCTION (DO NOT CHANGE NAME)
@api_view(['GET'])
@permission_classes([IsAuthenticated]) # IsTeacher permission agar hai toh add karein
def teacher_dashboard_metric(request):
    """
    Original method for Teacher Dashboard.
    Reverted to original name to avoid import errors and master branch clashes.
    """
    user = request.user
    
    total_courses = Course.objects.filter(teacher=user).count()
    
    # Total lectures generated by current teacher
    total_lectures = Lecture.objects.filter(generated_by=user).count()
    
    pending_validation_count = Lecture.objects.filter(
        generated_by=user, 
        validation_status='pending'
    ).count()
    
    total_validated_lectures = Lecture.objects.filter(
        generated_by=user,
        validation_status='validated'
    ).count()

    return Response({
        "total_courses": total_courses,
        "total_lectures_generated": total_lectures,
        "pending_validation_count": pending_validation_count,
        "total_validated_lectures": total_validated_lectures,
    })

